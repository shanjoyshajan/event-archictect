import React from 'react';
import { Printer, Download, Copy, Check, FileText } from 'lucide-react';
import { EventPlan } from '../types/event';
import { calculateBudgetSummary, formatCurrency } from '../utils/eventCalculations';

interface ExportSummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  event: EventPlan;
}

export const ExportSummaryModal: React.FC<ExportSummaryModalProps> = ({
  isOpen,
  onClose,
  event,
}) => {
  const [copied, setCopied] = React.useState(false);
  const summary = calculateBudgetSummary(event.budgetItems, event.targetBudget);

  if (!isOpen) return null;

  const handlePrint = () => {
    window.print();
  };

  const generateMarkdown = () => {
    return `# ${event.title}
**Event Type:** ${event.type}
**Date:** ${event.date}
**Location:** ${event.location}
**Guest Count:** ${event.guestCount}
**Target Budget:** ${formatCurrency(event.targetBudget, event.currency)}
**Style & Theme:** ${event.styleTheme}

---

## Master Day-of Run of Show
${event.dayOfSchedule.map(d => `- **${d.time}** (${d.durationMinutes} min): ${d.title} | Lead: ${d.leadPerson} | Loc: ${d.location}${d.notes ? `\n  *Notes: ${d.notes}*` : ''}`).join('\n')}

---

## Key Vendor Contacts
${event.vendors.map(v => `- **${v.businessName}** (${v.category}) - Contact: ${v.contactName} | Phone: ${v.phone} | Email: ${v.email} | Quote: ${formatCurrency(v.quotedAmount, event.currency)} | Status: ${v.status}`).join('\n')}

---

## Budget Summary
- **Target Budget:** ${formatCurrency(summary.targetBudget, event.currency)}
- **Committed Actual:** ${formatCurrency(summary.totalActual, event.currency)}
- **Total Paid:** ${formatCurrency(summary.totalPaid, event.currency)}
- **Unpaid Balance:** ${formatCurrency(summary.unpaidBalance, event.currency)}

---
*Generated by EventFlow AI Planner*
`;
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${event.title.toLowerCase().replace(/\s+/g, '_')}_itinerary.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs overflow-y-auto">
      <div className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-3xl max-h-[90vh] flex flex-col overflow-hidden">
        
        {/* Header */}
        <div className="p-4 bg-slate-50 border-b border-slate-200 flex items-center justify-between shrink-0">
          <div className="flex items-center gap-2">
            <FileText className="w-4 h-4 text-slate-700" />
            <h3 className="text-sm font-bold text-slate-900">
              Printable Master Event Packet &amp; Vendor Itinerary
            </h3>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyMarkdown}
              className="px-2.5 py-1.5 bg-white border border-slate-200 hover:bg-slate-100 rounded text-xs font-semibold text-slate-700 flex items-center gap-1.5"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy MD'}</span>
            </button>

            <button
              onClick={handleDownloadMarkdown}
              className="px-2.5 py-1.5 bg-white border border-slate-200 hover:bg-slate-100 rounded text-xs font-semibold text-slate-700 flex items-center gap-1.5"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download MD</span>
            </button>

            <button
              onClick={handlePrint}
              className="px-3 py-1.5 bg-slate-900 hover:bg-slate-800 text-white rounded text-xs font-semibold flex items-center gap-1.5 shadow-2xs"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print / Save PDF</span>
            </button>

            <button
              onClick={onClose}
              className="w-7 h-7 rounded text-slate-400 hover:text-slate-700 flex items-center justify-center text-xs font-bold"
            >
              ✕
            </button>
          </div>
        </div>

        {/* Printable Viewport */}
        <div className="p-8 overflow-y-auto space-y-6 text-xs text-slate-800 font-sans print:p-0">
          
          {/* Document Header */}
          <div className="border-b border-slate-200 pb-4 space-y-1">
            <div className="text-[10px] uppercase font-bold tracking-widest text-slate-400">
              Official Master Event Itinerary &amp; Logistics Sheet
            </div>
            <h1 className="text-2xl font-bold text-slate-900">{event.title}</h1>
            <div className="flex flex-wrap gap-4 text-slate-600 pt-1">
              <span><strong>Date:</strong> {event.date}</span>
              <span><strong>Location:</strong> {event.location}</span>
              <span><strong>Guests:</strong> {event.guestCount}</span>
              <span><strong>Budget:</strong> {formatCurrency(event.targetBudget, event.currency)}</span>
            </div>
            <div className="text-slate-500 pt-1">
              <strong>Theme:</strong> {event.styleTheme}
            </div>
          </div>

          {/* Emergency Contacts */}
          {event.emergencyContacts && event.emergencyContacts.length > 0 && (
            <div className="space-y-2">
              <h2 className="font-bold text-sm text-slate-900 uppercase tracking-wider text-[11px]">
                Key Event Contacts
              </h2>
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
                {event.emergencyContacts.map((c, i) => (
                  <div key={i} className="p-2.5 bg-slate-50 rounded border border-slate-200/80">
                    <div className="text-[10px] text-slate-400 font-semibold">{c.role}</div>
                    <div className="font-bold text-slate-900">{c.name}</div>
                    <div className="text-slate-600 font-mono text-[11px]">{c.phone}</div>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Master Run of Show */}
          <div className="space-y-2">
            <h2 className="font-bold text-sm text-slate-900 uppercase tracking-wider text-[11px]">
              Master Day-of Run of Show ({event.dayOfSchedule.length} Items)
            </h2>
            <table className="w-full text-left border-collapse border border-slate-200">
              <thead>
                <tr className="bg-slate-100 text-[11px] font-bold text-slate-700">
                  <th className="p-2 border border-slate-200">Time</th>
                  <th className="p-2 border border-slate-200">Program Event</th>
                  <th className="p-2 border border-slate-200">Lead Person</th>
                  <th className="p-2 border border-slate-200">Location</th>
                  <th className="p-2 border border-slate-200">Specific Cues / Notes</th>
                </tr>
              </thead>
              <tbody>
                {event.dayOfSchedule.map((d) => (
                  <tr key={d.id} className="border-b border-slate-100">
                    <td className="p-2 border border-slate-200 font-mono font-semibold tabular-nums text-slate-900 whitespace-nowrap">
                      {d.time} ({d.durationMinutes}m)
                    </td>
                    <td className="p-2 border border-slate-200 font-medium text-slate-900">{d.title}</td>
                    <td className="p-2 border border-slate-200 text-slate-700">{d.leadPerson}</td>
                    <td className="p-2 border border-slate-200 text-slate-600">{d.location}</td>
                    <td className="p-2 border border-slate-200 text-slate-500">{d.notes || '—'}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Vendor Sheet */}
          <div className="space-y-2">
            <h2 className="font-bold text-sm text-slate-900 uppercase tracking-wider text-[11px]">
              Contracted Vendors &amp; Partners
            </h2>
            <table className="w-full text-left border-collapse border border-slate-200">
              <thead>
                <tr className="bg-slate-100 text-[11px] font-bold text-slate-700">
                  <th className="p-2 border border-slate-200">Category</th>
                  <th className="p-2 border border-slate-200">Business / Contact</th>
                  <th className="p-2 border border-slate-200">Phone / Email</th>
                  <th className="p-2 border border-slate-200 text-right">Quote</th>
                  <th className="p-2 border border-slate-200 text-center">Status</th>
                </tr>
              </thead>
              <tbody>
                {event.vendors.map((v) => (
                  <tr key={v.id} className="border-b border-slate-100">
                    <td className="p-2 border border-slate-200 font-medium">{v.category}</td>
                    <td className="p-2 border border-slate-200">
                      <span className="font-bold text-slate-900">{v.businessName}</span>
                      <span className="text-slate-500 block text-[11px]">Attn: {v.contactName}</span>
                    </td>
                    <td className="p-2 border border-slate-200 font-mono text-[11px] text-slate-600">
                      <div>{v.phone}</div>
                      <div>{v.email}</div>
                    </td>
                    <td className="p-2 border border-slate-200 text-right font-mono tabular-nums font-semibold">
                      {formatCurrency(v.quotedAmount, event.currency)}
                    </td>
                    <td className="p-2 border border-slate-200 text-center uppercase text-[10px] font-semibold text-slate-600">
                      {v.status}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Budget Grand Summary */}
          <div className="p-4 bg-slate-50 rounded-xl border border-slate-200 flex flex-wrap items-center justify-between gap-4">
            <div>
              <div className="text-[10px] text-slate-400 uppercase font-bold">Financial Summary</div>
              <div className="text-sm font-bold text-slate-900">
                Target Budget: {formatCurrency(summary.targetBudget, event.currency)}
              </div>
            </div>
            <div className="flex gap-6 text-slate-700">
              <div>
                <span className="text-[10px] text-slate-400 block">Committed Actual</span>
                <span className="font-mono font-bold text-slate-900">{formatCurrency(summary.totalActual, event.currency)}</span>
              </div>
              <div>
                <span className="text-[10px] text-slate-400 block">Total Paid Out</span>
                <span className="font-mono font-bold text-emerald-700">{formatCurrency(summary.totalPaid, event.currency)}</span>
              </div>
              <div>
                <span className="text-[10px] text-slate-400 block">Balance Remaining</span>
                <span className="font-mono font-bold text-slate-800">{formatCurrency(summary.unpaidBalance, event.currency)}</span>
              </div>
            </div>
          </div>

        </div>

      </div>
    </div>
  );
};
